/* ตัวแปลข้อความเดียว: ไม่มีภาษาไทย = ปล่อยผ่าน · เว้นวรรคหน้า/หลังข้อความต้องคงไว้
   (ข้อความที่ถูกผ่าซีกด้วยตัวแปร เช่น "ผ่าน {n} คน" จะมาเป็นชิ้น "ผ่าน " กับ " คน") */
export function tr(text, lang) {
  if (lang !== 'EN' || typeof text !== 'string' || !THAI.test(text)) return text;
  const core = text.trim();
  const hit = EN[core] ?? EN[text];
  if (hit === undefined) return text;
  const lead = text.slice(0, text.length - text.trimStart().length);
  const tail = text.slice(text.trimEnd().length);
  return lead + hit + tail;
}

// prop ที่เป็นข้อความโชว์บนจอ (นอกจาก children) — ใช้ภาษาไทยปนอยู่เมื่อไหร่ ก็แปลทุก prop ที่เป็น string/element
/* เดินดู React element ทั้งต้น แล้วแปลข้อความไทยทุกจุด (children, และ prop ที่เป็นข้อความหรือเป็น element เช่น footer)
   ไม่แตะ prop ที่เป็นฟังก์ชัน/ออบเจ็กต์ (style ฯลฯ) */
export function translateNode(node, lang) {
  if (lang !== 'EN') return node;
  if (typeof node === 'string') return tr(node, lang);
  if (Array.isArray(node)) return node.map((child) => translateNode(child, lang));
  if (!isValidElement(node)) return node;

  const props = node.props;
  // data-en="..." = ข้อความอังกฤษเฉพาะจุดนี้ — ใช้เมื่อคำไทยเดียวกันแปลต่างกันตามบริบท
  // (เช่น "ถอนสิทธิ์" ของนักศึกษา = Revoke access แต่ของบัญชีผู้ใช้ = Close account ตามที่ระบบจริงเขียน)
  if (typeof props['data-en'] === 'string') return cloneElement(node, {}, props['data-en']);
  const changed = {};
  for (const key of Object.keys(props)) {
    if (key === 'children') continue;
    const value = props[key];
    if (typeof value === 'string' && THAI.test(value)) changed[key] = tr(value, lang);
    else if (isValidElement(value) || Array.isArray(value)) changed[key] = translateNode(value, lang);
  }

  const kids = props.children;
  if (kids === undefined) return cloneElement(node, changed);
  // ส่งลูกเป็น argument แยกตัว (ไม่ใช่ array ใน props) เพื่อไม่ให้ React ฟ้องเรื่อง key ซ้ำ
  const list = Array.isArray(kids) ? kids : [kids];
  return cloneElement(node, changed, ...list.map((child) => translateNode(child, lang)));
}

