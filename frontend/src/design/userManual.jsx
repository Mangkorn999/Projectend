export function OfficerManual() {
  // เปิดหัวข้อแรกไว้เป็นตัวอย่างตอนเข้าหน้าครั้งแรก ที่เหลือพับไว้ก่อน
  const [open, setOpen] = useState(() => new Set(['dashboard']));
  const toggle = (key) => setOpen(prev => {
    const next = new Set(prev);
    next.has(key) ? next.delete(key) : next.add(key);
    return next;
  });

  return (
    <div className="fade-up">
      <PageHead title="คู่มือการใช้งาน" sub="สำหรับเจ้าหน้าที่คณะ — คลิกหัวข้อเพื่อดูรายละเอียด" />
      <div style={{ display: 'flex', flexDirection: 'column', gap: 12 }}>
        {SECTIONS.map(s => (
          <div key={s.key} className="card" style={{ padding: 0, overflow: 'hidden' }}>
            <button type="button" onClick={() => toggle(s.key)}
              style={{ width: '100%', display: 'flex', justifyContent: 'space-between', alignItems: 'center',
                padding: '16px 20px', border: 'none', background: 'transparent', cursor: 'pointer',
                textAlign: 'left', fontFamily: 'inherit' }}>
              <span style={{ fontSize: 16.5, fontWeight: 700, color: 'var(--ink-900)' }}>{s.title}</span>
              <Icon name="chevD" size={18} style={{ color: 'var(--ink-400)', flex: 'none',
                transform: open.has(s.key) ? 'rotate(180deg)' : 'none', transition: '.15s' }} />
            </button>
            {open.has(s.key) && (
              <div style={{ padding: '0 20px 20px', color: 'var(--ink-700)', fontSize: 15, lineHeight: 1.8 }}>
                {s.body}
              </div>
            )}
          </div>
        ))}
      </div>
    </div>
  );
}
